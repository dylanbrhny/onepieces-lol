#!/usr/bin/env python3
"""Build the hand-curated prompt bank: data/question_bank.csv -> data/question_bank.js

Run from the log-pose folder (after tools/scrape_wiki.py, which fills the wiki cache):
    python3 -I tools/build_bank.py

data/question_bank.csv, one row per prompt (edit it in a spreadsheet):
  key         unique id, e.g. "marines" (never reuse one for a different prompt)
  prompt      what the player sees: "Name a Marine, past or present"
  group       topic, so a day never gets two prompts on the same topic: org, rank, battle, family...
  difficulty  easy / medium / hard  (which difficulty's daily and Endless use it)
  min_ep      anime episode after which the prompt text spoils nothing (0 = always safe);
              players whose spoiler filter is earlier never see it
  categories  One Piece Wiki categories joined with |  -> every character in them is a right answer
  answers     character ids joined with |               -> extra right answers (or the whole list)
  remove      character ids joined with |               -> never a right answer, even if a category has them
  source      where it came from (wiki / claude), for your reference

A prompt needs 5+ right answers (after the spoiler filter, on each difficulty) to be played.
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import tag_characters as T  # noqa: E402  (reads the scraper's cached wiki pages)

BANK = os.path.join(ROOT, "data", "question_bank.csv")
OUT = os.path.join(ROOT, "data", "question_bank.js")
MIN_ANSWERS = 5


def split(v):
    return [x.strip() for x in (v or "").split("|") if x.strip()]


def main():
    chars = list(csv.DictReader(open(os.path.join(ROOT, "data", "characters.csv"), encoding="utf-8-sig")))
    ids = {c["id"] for c in chars}
    url2id = {c.get("wiki_url", ""): c["id"] for c in chars}
    print("reading cached wiki categories")
    members = {}
    for p in T.load_pages().values():
        cid = url2id.get(p.get("url", ""))
        if cid:
            for cat in p["cats"]:
                members.setdefault(cat, set()).add(cid)

    out, problems, keys = [], [], set()
    for line, r in enumerate(csv.DictReader(open(BANK, encoding="utf-8-sig")), start=2):
        key, text = (r.get("key") or "").strip(), (r.get("prompt") or "").strip()
        if not key or not text:
            continue
        if key in keys:
            problems.append(f"row {line}: duplicate key '{key}'")
            continue
        keys.add(key)
        answers = set()
        for cat in split(r.get("categories")):
            if cat not in members:
                problems.append(f"{key}: no characters in wiki category '{cat}'")
            answers |= members.get(cat, set())
        for cid in split(r.get("answers")):
            if cid in ids:
                answers.add(cid)
            else:
                problems.append(f"{key}: unknown character id '{cid}'")
        answers -= set(split(r.get("remove")))
        if len(answers) < MIN_ANSWERS:
            problems.append(f"{key}: only {len(answers)} right answers (needs {MIN_ANSWERS}), skipped")
            continue
        diff = (r.get("difficulty") or "").strip().lower()
        try:
            min_ep = int(float(r.get("min_ep") or 0))
        except ValueError:
            min_ep = 0
        q = {"id": "bank:" + key, "group": "bank:" + ((r.get("group") or "other").strip() or "other"),
             "text": text, "where": [["id", "in", sorted(answers)]]}
        if diff in ("easy", "medium", "hard"):
            q["difficulty"] = diff
        if min_ep > 0:
            q["min_ep"] = min_ep
        out.append(q)

    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_bank.py from data/question_bank.csv. Edit the CSV, not this file.\n")
        f.write("window.QUESTIONS = (window.QUESTIONS || []).concat(")
        json.dump(out, f, ensure_ascii=False, separators=(",", ":"))
        f.write(");\n")
    os.replace(tmp, OUT)
    for p in problems[:40]:
        print("note:", p)
    if len(problems) > 40:
        print(f"... and {len(problems) - 40} more notes")
    by = {}
    for q in out:
        by[q.get("difficulty", "auto")] = by.get(q.get("difficulty", "auto"), 0) + 1
    print(f"Wrote {len(out)} prompts to data/question_bank.js  {by}")


if __name__ == "__main__":
    main()
