#!/usr/bin/env python3
"""Turn logged player answers into data/answer_stats.js (how often each answer was given per prompt).

The game logs every finished answer as JSON: {"prompt", "answer", "ok", "day", "kind", ...}
(see logAnswer in js/app.js). Collect those wherever you like (a Google Sheet via Apps Script,
a database export, or a browser's localStorage "logpose-v2:answerLog") and save them as
a .jsonl (one JSON per line), .json (a list) or .csv (columns prompt, answer, ok).

    python3 -I tools/aggregate_answers.py answers.jsonl [more files...]

Only right answers count. The game blends these counts into each prompt's order:
the more often an answer is given, the closer it slides to Rookie. Weight grows with plays
(GAME_CONFIG.statsFullPlays) and never passes GAME_CONFIG.statsMaxWeight (half by default),
so the wiki-based order still decides most of it.
"""
import csv
import json
import os
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(path):
    if path.endswith(".csv"):
        with open(path, encoding="utf-8-sig", newline="") as f:
            for r in csv.DictReader(f):
                yield {"prompt": r.get("prompt"), "answer": r.get("answer"), "difficulty": r.get("difficulty", ""),
                       "ok": str(r.get("ok", "")).lower() in ("true", "1", "yes")}
        return
    text = open(path, encoding="utf-8").read().strip()
    if text.startswith("["):
        yield from json.loads(text)
    else:
        for line in text.splitlines():
            if line.strip():
                yield json.loads(line)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    plays, counts = Counter(), defaultdict(Counter)
    mplays, mcounts = defaultdict(Counter), defaultdict(lambda: defaultdict(Counter))   # per difficulty
    for path in sys.argv[1:]:
        for r in read(path):
            p, a = r.get("prompt"), r.get("answer")
            if not p:
                continue
            m = str(r.get("difficulty") or "").lower()
            m = "easy" if m == "supereasy" else m
            plays[p] += 1
            if m:
                mplays[p][m] += 1
            if a and r.get("ok"):
                counts[p][a] += 1
                if m:
                    mcounts[p][m][a] += 1
    stats = {p: {"plays": plays[p], "counts": dict(counts[p].most_common()),
                 "modes": {m: {"plays": n, "counts": dict(mcounts[p][m].most_common())} for m, n in mplays[p].items()}}
             for p in plays}
    out = os.path.join(ROOT, "data", "answer_stats.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/aggregate_answers.py: how often each answer was given per prompt.\n")
        f.write("window.ANSWER_STATS = ")
        json.dump(stats, f, ensure_ascii=False)
        f.write(";\n")
    print(f"Wrote data/answer_stats.js: {len(stats)} prompts, {sum(plays.values())} answers")


if __name__ == "__main__":
    main()
